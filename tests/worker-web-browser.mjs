import assert from 'node:assert/strict';
import fs from 'node:fs';
import { chromium } from 'playwright';
const baseUrl = process.env.SAATHI_BASE_URL || 'http://localhost:3001';
const origin = new URL(baseUrl).origin;
const executablePath = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || undefined;
const browser = await chromium.launch({ executablePath, headless: true, args: ['--no-sandbox'] });
fs.mkdirSync('outputs', { recursive: true });
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const page = await context.newPage();
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(baseUrl);
  await page.getByRole('heading', { name: 'अपनी भाषा चुनें' }).waitFor();
  await page.screenshot({ path: 'outputs/saathi-language-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'English' }).click();
  await page.getByRole('button', { name: 'Continue' }).click();
  await page.getByLabel('Mobile number').fill('9876543211');
  await page.getByRole('button', { name: 'Send OTP', exact: true }).click();
  await page.getByLabel('Verification code').fill('123456');
  await page.getByRole('button', { name: 'Verify & continue' }).click();
  await page.getByRole('heading', { name: 'Hello, Meera' }).waitFor();
  await page.screenshot({ path: 'outputs/saathi-home-mobile.png', fullPage: true });
  const nav = page.getByRole('navigation');
  await nav.getByRole('button', { name: 'Profile', exact: true }).click();
  await page.getByLabel('Your skills').fill('Browser verified childcare and cleaning');
  await page.getByLabel('Age', { exact: true }).fill('32');
  await page.getByRole('button', { name: 'Save my profile', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Profile saved' }).waitFor();
  await page.reload();
  await nav.getByRole('button', { name: 'Profile', exact: true }).click();
  assert.equal(await page.getByLabel('Your skills').inputValue(), 'Browser verified childcare and cleaning');
  assert.equal(await page.getByLabel('Age', { exact: true }).inputValue(), '32');
  await page.getByRole('button', { name: 'Next: upload documents' }).click();
  await page.getByLabel('Photo', { exact: true }).setInputFiles({ name: 'photo.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aKqkAAAAASUVORK5CYII=', 'base64') });
  await page.getByRole('status').filter({ hasText: 'Document submitted securely' }).waitFor();
  await page.getByText('Under review', { exact: true }).waitFor();
  await nav.getByRole('button', { name: 'Jobs', exact: true }).click();
  await page.getByRole('button', { name: 'View job' }).first().click();
  await page.getByRole('button', { name: 'View duty card' }).click();
  await page.getByText('Your work — clear and in writing').waitFor();
  await page.getByRole('button', { name: 'Interested', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Your application has been sent.' }).waitFor();
  await page.screenshot({ path: 'outputs/saathi-duty-mobile.png', fullPage: true });
  // Offer the job as its actual owner, then accept it through the worker UI.
  const me = await (await context.request.get(origin + '/api/marketplace/me')).json();
  const application = me.applications[0];
  const family = await browser.newContext();
  await family.request.post(origin + '/api/auth/request-otp', { data: { phone: '9876543210' } });
  await family.request.post(origin + '/api/auth/verify-otp', { data: { phone: '9876543210', code: '123456' } });
  const offer = await family.request.post(`${origin}/api/marketplace/applications/${application.id}/status`, { data: { action: 'offer' } });
  assert.equal(offer.status(), 200);
  await page.reload();
  await nav.getByRole('button', { name: 'Jobs', exact: true }).click();
  await page.locator('.applications').getByRole('button').first().click();
  await page.getByRole('button', { name: 'I agree to the duties — accept offer' }).click();
  await page.getByText('Currently working', { exact: true }).waitFor();
  await page.screenshot({ path: 'outputs/saathi-current-mobile.png', fullPage: true });
  await nav.getByRole('button', { name: 'Help', exact: true }).click();
  await page.getByLabel('What do you need help with?').selectOption('SALARY');
  await page.getByLabel('Tell us what happened').fill('Please help with salary confirmation for this month.');
  await page.getByRole('button', { name: 'Send request', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Request submitted' }).waitFor();
  await page.getByText('Please help with salary confirmation for this month.', { exact: true }).first().waitFor();
  await page.screenshot({ path: 'outputs/saathi-help-mobile.png', fullPage: true });
  for (const width of [360, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `No overflow at ${width}px`);
  }
  await nav.getByRole('button', { name: 'Home', exact: true }).click();
  await page.screenshot({ path: 'outputs/saathi-home-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'हिंदी', exact: true }).click();
  await page.getByRole('heading', { name: 'नमस्ते, Meera' }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'outputs/saathi-home-hindi.png', fullPage: true });
  await page.getByRole('button', { name: 'English', exact: true }).click();
  await nav.getByRole('button', { name: 'Profile', exact: true }).click();
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await page.getByRole('heading', { name: 'Login with your mobile' }).waitFor();
  assert.deepEqual(errors, []);
  console.log('PASS: Saathi language, OTP/cookie proxy, persisted profile and age, private photo upload, job application, duty card, offer acceptance/current job, support request, Hindi switch, logout and 360–1440px layouts.');
  await family.close();
} finally { await browser.close(); }

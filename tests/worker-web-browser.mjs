import assert from 'node:assert/strict';
import fs from 'node:fs';
import { chromium } from 'playwright';
const executablePath = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe';
const browser = await chromium.launch({ executablePath, headless: true });
fs.mkdirSync('outputs', { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://localhost:3001');
  await page.getByRole('heading', { name: 'Let’s get started' }).waitFor();
  await page.screenshot({ path: 'outputs/worker-web-welcome.png', fullPage: true });
  await page.getByLabel('Mobile number').fill('9876543211');
  await page.getByRole('button', { name: 'Send verification code' }).click();
  await page.getByLabel('Verification code').fill('123456');
  await page.getByRole('button', { name: 'Verify & continue' }).click();
  await page.getByRole('heading', { name: 'Hello, Meera.' }).waitFor();
  await page.getByText('Approved', { exact: true }).waitFor();
  await page.screenshot({ path: 'outputs/worker-web-overview.png', fullPage: true });
  await page.getByRole('navigation').getByRole('button', { name: 'My profile', exact: false }).click();
  await page.getByLabel('Your skills').fill('Browser verified cooking and laundry');
  await page.getByRole('button', { name: 'Save my profile' }).click();
  await page.getByRole('status').filter({ hasText: 'Your profile has been saved.' }).waitFor();
  await page.getByRole('radio', { name: 'Taking a break' }).check();
  await page.getByRole('button', { name: 'Save my profile' }).click();
  await page.waitForTimeout(600);
  await page.reload();
  await page.getByRole('heading', { name: 'Hello, Meera.' }).waitFor();
  assert.equal(await page.getByText('Taking a break', { exact: true }).count(), 1);
  await page.getByRole('navigation').getByRole('button', { name: 'My profile', exact: false }).click();
  assert.equal(await page.getByLabel('Your skills').inputValue(), 'Browser verified cooking and laundry');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'No mobile horizontal overflow');
  await page.screenshot({ path: 'outputs/worker-web-mobile-profile.png', fullPage: true });
  await page.getByRole('button', { name: 'Interviews', exact: false }).click();
  await page.getByRole('heading', { name: 'Interview invitations', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Sign out' }).click();
  await page.getByRole('heading', { name: 'Let’s get started' }).waitFor();
  await page.getByLabel('Mobile number').fill('9876543213');
  await page.getByRole('button', { name: 'Send verification code' }).click();
  await page.getByLabel('Verification code').fill('123456');
  await page.getByRole('button', { name: 'Verify & continue' }).click();
  await page.getByRole('button', { name: 'Create my profile' }).click();
  await page.getByLabel('Full name').fill('New Worker Browser');
  await page.getByRole('button', { name: 'Submit for review' }).click();
  await page.getByRole('status').filter({ hasText: 'Profile submitted' }).waitFor();
  assert.deepEqual(errors, []);
  console.log('PASS: worker browser login, cookie proxy, profile save, availability persistence, mobile layout, invitations, logout, and new registration.');
} finally { await browser.close(); }

